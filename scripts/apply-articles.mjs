/*
 * Turn .vuepress/articles.json into the three artifacts that must agree:
 *
 *   1. `permalink` frontmatter on every article, so URLs are ASCII and stable.
 *      Site config uses `permalink: "/:slug"`, and with Chinese filenames that
 *      yields percent-encoded gibberish (/models/%E5%B0%8F%E7%B1%B3…); an ASCII
 *      slug is what lets the model-world button build a link without guessing.
 *   2. .vuepress/sidebars/models.ts, in the order articles.json declares. The
 *      upstream generator sorted by file birthtime, which no fresh clone can
 *      reproduce, so ordering had to become explicit.
 *   3. guide-model-map.json: model slug -> article URL. Published for the
 *      ai-model-world repo so its 查看评测文章 button resolves per model
 *      (Q18=C) instead of always pointing at one fixed collection page.
 *
 * Idempotent and validating: it refuses to run if a model is claimed by two
 * articles, if a declared file is missing, or if the directory holds a file
 * that articles.json does not mention.
 */
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const SECTION = 'Vibe Coding 零基础教程/15 模型动态';
const articles = JSON.parse(await readFile('.vuepress/articles.json', 'utf8'));
const base = process.env.GUIDE_BASE_URL || '';

const files = (await readdir(SECTION)).filter((f) => f.endsWith('.md')).sort();
const declared = articles.articles.map((a) => a.file);

const missing = declared.filter((f) => !files.includes(f));
const undeclared = files.filter((f) => !declared.includes(f));
if (missing.length) throw new Error('articles.json names files that do not exist: ' + missing.join(', '));
if (undeclared.length) throw new Error('directory has files missing from articles.json: ' + undeclared.join(', '));

// one article per model, or the deep link is a coin flip
const claims = new Map();
for (const a of articles.articles) {
  for (const m of a.models || []) {
    if (claims.has(m)) throw new Error(`model ${m} claimed by both "${claims.get(m)}" and "${a.file}"`);
    claims.set(m, a);
  }
}

const paths = new Set();
for (const a of articles.articles) {
  if (paths.has(a.path)) throw new Error('duplicate permalink ' + a.path);
  paths.add(a.path);
}

for (const a of articles.articles) {
  const file = path.join(SECTION, a.file);
  const original = await readFile(file, 'utf8');
  const fm = [`permalink: ${a.path}`];
  if (a.title) fm.push(`title: "${a.title.replace(/"/g, '\\"')}"`);

  let body = original;
  let existing = null;
  if (body.startsWith('---\n')) {
    const end = body.indexOf('\n---', 4);
    if (end !== -1) {
      existing = body.slice(4, end + 1);
      body = body.slice(end + 5).replace(/^\n/, '');
    }
  }
  const keep = (existing || '')
    .split('\n')
    .filter((line) => line && !/^permalink:/.test(line) && !/^title:/.test(line));
  const block = ['---', ...fm, ...keep, '---'].join('\n');
  await writeFile(file, block + '\n' + body);
}

/*
 * Sidebar entries are matched against a page's `regularPath` (its path on disk),
 * *not* the permalink - see theme-default/util resolvePage/resolveMatchingConfig.
 * Keying this by "/models/" therefore matched nothing and VuePress silently fell
 * back to "auto", which renders the current page's own headings instead of the
 * list of sibling articles: the guide looked fine but had no way to move between
 * articles. So the children are declared as absolute on-disk paths under the
 * Chinese section directory, and VuePress maps each one back to its permalink.
 */
const sidebar = {
  '/': [
    {
      title: '模型动态',
      collapsable: false,
      children: articles.articles.map((a) => `${SECTION}/${a.file.replace(/\.md$/, '')}`),
    },
  ],
};
await mkdir('.vuepress/sidebars', { recursive: true });
await writeFile(
  '.vuepress/sidebars/models.ts',
  '// generated by scripts/apply-articles.mjs from .vuepress/articles.json - do not edit\n' +
    'export default ' +
    JSON.stringify(sidebar, null, 2) +
    ';\n',
);

const map = {
  generatedFrom: 'ai-guide 15 模型动态 (migrated snapshot)',
  baseUrl: base,
  collection: base + articles.collection,
  models: Object.fromEntries([...claims.entries()].map(([slug, a]) => [slug, base + a.path])),
};
await writeFile('guide-model-map.json', JSON.stringify(map, null, 2) + '\n');

console.log(
  JSON.stringify(
    {
      articles: articles.articles.length,
      permalinksWritten: articles.articles.length,
      modelsMapped: claims.size,
      unclaimedArticles: articles.articles.filter((a) => !(a.models || []).length).map((a) => a.file),
    },
    null,
    2,
  ),
);
